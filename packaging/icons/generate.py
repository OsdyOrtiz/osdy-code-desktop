#!/usr/bin/env python3
"""Wraps the mascot PNG (argv[1], rasterized by generate.sh from
assets/mascot/osdy-code-mapache-ambar.svg) in the macOS squircle template (icon.svg).

An 824 px continuous-corner body is inset by 100 px on a transparent 1024 px
canvas, leaving room for the baked-in drop shadow.

Standard library only; run through generate.sh, which also rasterizes.
"""

import base64
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent / "icon.svg"

CANVAS = 1024
BODY = 824
INSET = (CANVAS - BODY) / 2
# Superellipse exponent approximating Apple's continuous corners (~22% radius).
SQUIRCLE_N = 4.6


def squircle_path(half, dy=0.0):
    cx = CANVAS / 2
    cy = CANVAS / 2 + dy
    points = []
    steps = 720
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + half * math.copysign(abs(c) ** (2 / SQUIRCLE_N), c)
        y = cy + half * math.copysign(abs(s) ** (2 / SQUIRCLE_N), s)
        points.append(f"{x:.2f},{y:.2f}")
    return "M" + " L".join(points) + " Z"


def main():
    source = pathlib.Path(sys.argv[1])
    mascot = base64.b64encode(source.read_bytes()).decode("ascii")
    body = squircle_path(BODY / 2)
    # AppKit ignores filters and path fill-opacity. Stack progressively larger
    # squircles with a constant-opacity gradient fill to get a soft shadow.
    shadow = "\n".join(
        f'    <path d="{squircle_path(BODY / 2 + k * 1.6, 3 + k * 1.8)}"/>'
        for k in range(10)
    )
    svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by packaging/icons/generate.sh from assets/mascot/osdy-code-mapache-ambar.svg. Do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
  <defs>
    <linearGradient id="shadow">
      <stop offset="0" stop-color="#000000" stop-opacity="0.028"/>
      <stop offset="1" stop-color="#000000" stop-opacity="0.028"/>
    </linearGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.10"/>
      <stop offset="0.45" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <clipPath id="body"><path d="{body}"/></clipPath>
  </defs>
  <g fill="url(#shadow)">
{shadow}
  </g>
  <g clip-path="url(#body)">
    <image x="{INSET:g}" y="{INSET:g}" width="{BODY}" height="{BODY}" xlink:href="data:image/png;base64,{mascot}"/>
    <rect x="{INSET:g}" y="{INSET:g}" width="{BODY}" height="{BODY}" fill="url(#sheen)"/>
  </g>
</svg>
"""
    OUT.write_text(svg, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Regenerate raccoon_dots.rs from the still badge, using only Python's stdlib."""

import struct
import zlib
from pathlib import Path


def rgba_png(data):
    """Read rows of the source's non-interlaced, 8-bit RGBA PNG format."""
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    offset, compressed = 8, bytearray()
    while offset < len(data):
        length, tag = struct.unpack_from(">I4s", data, offset)
        chunk = data[offset + 8 : offset + 8 + length]
        if tag == b"IHDR":
            w, h, *format_bytes = struct.unpack(">IIBBBBB", chunk)
            assert format_bytes == [8, 6, 0, 0, 0]
        elif tag == b"IDAT":
            compressed.extend(chunk)
        offset += length + 12
    raw = zlib.decompress(compressed)
    stride = 4 * w + 1
    assert len(raw) == stride * h
    rows, above = [], bytearray(4 * w)
    for y in range(h):
        start = y * stride
        kind, row = raw[start], bytearray(raw[start + 1 : start + stride])
        for i, value in enumerate(row):
            a = row[i - 4] if i >= 4 else 0
            b = above[i]
            c = above[i - 4] if i >= 4 else 0
            if kind == 4:  # Paeth predictor; ties prefer left, then up.
                p = a + b - c
                prediction = min((a, b, c), key=lambda n: abs(p - n))
            else:
                prediction = (0, a, b, (a + b) // 2)[kind]
            row[i] = (value + prediction) & 255
        rows.append(row)
        above = row
    return rows


def generate(image):
    # Center the crop on the head, not the disc. Downsample by averaging
    # source pixels; ignore the dark backdrop and the ring outside the disc.
    def light(x, y):
        if (x - 191.5) ** 2 + (y - 192) ** 2 > 132**2:
            return 0
        r, g, b, a = image[y][4 * x : 4 * x + 4]
        return ((2 * r + 6 * g + 2 * b) * a) // 2550

    rows = []
    for y in range(68):
        row = []
        for x in range(80):
            pixels = [
                light(sx, sy)
                for sy in range(89 + y * 16 // 5, 89 + (y + 1) * 16 // 5)
                for sx in range(64 + x * 16 // 5, 64 + (x + 1) * 16 // 5)
            ]
            luma = sum(pixels) // len(pixels)
            row.append(str(sum(luma >= threshold for threshold in (79, 116, 156, 180))))
        rows.append(f'    b"{"".join(row)}",')
    return (
        "// Generated by generate_raccoon_dots.py; 0 is empty, 1–4 are ink shades.\n"
        "const RACCOON: &[&[u8; 80]; 68] = &[\n" + "\n".join(rows) + "\n];\n"
    )


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    badge = here.parents[2] / "assets" / "brand" / "badge-still.png"
    (here / "raccoon_dots.rs").write_text(generate(rgba_png(badge.read_bytes())), encoding="utf-8")
